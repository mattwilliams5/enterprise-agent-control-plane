"""Persistent routing preference and explicit, gated primary failback.

Probes must be performed by a trusted caller against an authenticated health
endpoint verifying application readiness and ledger access. HTTP 200 alone is
not proof of those properties. No probes are generated by this module.
"""
from __future__ import annotations

import sqlite3
import time
from pathlib import Path


class RegionalHealth:
    def __init__(self, db_path, *, clock=None, min_primary_probes=3, hold_seconds=60):
        if isinstance(min_primary_probes, bool) or not isinstance(min_primary_probes, int) or min_primary_probes < 1:
            raise ValueError('min_primary_probes must be positive')
        if hold_seconds < 0:
            raise ValueError('hold_seconds must not be negative')
        self.path = Path(db_path)
        if not self.path.is_file():
            raise FileNotFoundError(self.path)
        self.clock = clock or time.time
        self.min_primary_probes = min_primary_probes
        self.hold_seconds = hold_seconds
        self.db = sqlite3.connect(self.path, isolation_level=None, timeout=5)
        self.db.execute('PRAGMA busy_timeout=5000')
        self.db.execute('''CREATE TABLE IF NOT EXISTS regional_health (
            singleton INTEGER PRIMARY KEY CHECK(singleton=1),
            mode TEXT NOT NULL CHECK(mode IN ('primary', 'recovery')),
            changed_at REAL NOT NULL,
            primary_probe_streak INTEGER NOT NULL DEFAULT 0,
            last_primary_probe REAL,
            reason TEXT
        )''')
        self.db.execute('''INSERT OR IGNORE INTO regional_health
            (singleton, mode, changed_at, reason) VALUES (1, 'primary', ?, 'initial')''',
            (float(self.clock()),))

    def close(self):
        self.db.close()

    def snapshot(self):
        row = self.db.execute('''SELECT mode, changed_at, primary_probe_streak,
                    last_primary_probe, reason FROM regional_health WHERE singleton=1''').fetchone()
        return dict(zip(('mode', 'changed_at', 'primary_probe_streak', 'last_primary_probe', 'reason'), row))

    def enter_recovery(self, reason):
        """Only call after confirmed recovery-region acknowledgment or operator action."""
        if not reason:
            raise ValueError('A reason is required')
        now = float(self.clock())
        with self.db:
            self.db.execute('''UPDATE regional_health SET mode='recovery', changed_at=?,
                primary_probe_streak=0, last_primary_probe=NULL, reason=?
                WHERE singleton=1 AND mode != 'recovery' ''', (now, reason))
        return self.snapshot()

    def record_primary_probe(self, healthy: bool):
        if not isinstance(healthy, bool):
            raise TypeError('healthy must be boolean')
        now = float(self.clock())
        with self.db:
            self.db.execute('''UPDATE regional_health SET
                primary_probe_streak=CASE WHEN ? THEN primary_probe_streak+1 ELSE 0 END,
                last_primary_probe=? WHERE singleton=1 AND mode='recovery' ''',
                (healthy, now))
        return self.snapshot()

    def failback_if_ready(self):
        """Explicit failback, never implicit on a successful probe alone."""
        now = float(self.clock())
        with self.db:
            result = self.db.execute('''UPDATE regional_health
                SET mode='primary', changed_at=?, primary_probe_streak=0,
                    reason='controlled_failback'
                WHERE singleton=1 AND mode='recovery'
                  AND primary_probe_streak >= ? AND changed_at <= ?
                  AND last_primary_probe IS NOT NULL''',
                (now, self.min_primary_probes, now - self.hold_seconds))
        return result.rowcount == 1
